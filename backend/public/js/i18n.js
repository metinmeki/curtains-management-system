const originalTextNodes = new WeakMap();

function getLanguage() {
  return localStorage.getItem('language') || 'en';
}

function setLanguage(language) {
  localStorage.setItem('language', language);
  applyLanguage();
}

function translateText(text, language) {
  if (language === 'en') return text;
  return translations[language] && translations[language][text.trim()] ? translations[language][text.trim()] : text;
}

function translatePlaceholder(value, language) {
  if (!value || language === 'en') return value;
  return translations[language] && translations[language][value.trim()] ? translations[language][value.trim()] : value;
}

function translateNode(node, language) {
  if (node.nodeType === Node.TEXT_NODE) {
    const original = originalTextNodes.get(node) || node.textContent;

    if (original.trim()) {
      originalTextNodes.set(node, original);
      node.textContent = original.replace(original.trim(), translateText(original, language));
    }
    return;
  }

  if (node.nodeType !== Node.ELEMENT_NODE) return;
  if (['SCRIPT', 'STYLE'].includes(node.tagName)) return;

  if (node.placeholder) {
    if (!node.dataset.i18nOriginalPlaceholder) node.dataset.i18nOriginalPlaceholder = node.placeholder;
    node.placeholder = translatePlaceholder(node.dataset.i18nOriginalPlaceholder, language);
  }

  Array.from(node.childNodes).forEach(child => translateNode(child, language));
}

function addLanguageSwitcher() {
  if (document.getElementById('languageSwitcher')) return;

  const switcher = document.createElement('div');
  switcher.id = 'languageSwitcher';
  switcher.className = 'language-switcher';
  switcher.innerHTML = `
    <button type="button" data-lang="en">EN</button>
    <button type="button" data-lang="ar">عربي</button>
  `;

  switcher.querySelectorAll('button').forEach(button => {
    button.addEventListener('click', () => setLanguage(button.dataset.lang));
  });

  const navTarget = document.querySelector('.user-section') || document.querySelector('.navbar-actions');
  const loginCard = document.querySelector('.login-card');

  if (navTarget) {
    navTarget.prepend(switcher);
  } else if (loginCard) {
    loginCard.prepend(switcher);
  }
}

function applyLanguage() {
  const language = getLanguage();
  document.documentElement.lang = language;
  document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
  document.body.classList.toggle('ltr', language !== 'ar');
  document.body.classList.toggle('rtl', language === 'ar');

  addLanguageSwitcher();

  document.querySelectorAll('#languageSwitcher button').forEach(button => {
    button.classList.toggle('active', button.dataset.lang === language);
  });

  translateNode(document.body, language);
}

document.addEventListener('DOMContentLoaded', () => {
  applyLanguage();

  const observer = new MutationObserver(mutations => {
    if (!mutations.some(mutation => mutation.addedNodes.length)) return;
    mutations.forEach(mutation => {
      mutation.addedNodes.forEach(node => translateNode(node, getLanguage()));
    });
  });

  observer.observe(document.body, {
    childList: true,
    subtree: true
  });
});
